"""Run attacks A1-A9 in both modes and write the results table.

    python attacks/run_all.py                       # prints the table, writes docs/results.md
    python attacks/run_all.py --mode aimfa --out build/results.md

Everything runs in-process on throwaway temp stacks: no services, no network, no real data.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Callable, Iterable
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:  # so `python attacks/run_all.py` finds aimfa + attacks
    sys.path.insert(0, str(REPO_ROOT))

from attacks import (  # noqa: E402
    a1_tampered_agent,
    a2_stolen_token,
    a3_replay,
    a4_prompt_injection,
    a5_unauthorized_wire,
    a6_expired_token,
    a7_scope_escalation,
    a8_audit_tamper,
    a9_fake_approval,
)
from attacks.common import MODE_AIMFA, MODE_BASELINE, MODES, AttackResult  # noqa: E402

ATTACKS: tuple[Callable[[str], AttackResult], ...] = tuple(
    m.run
    for m in (
        a1_tampered_agent,
        a2_stolen_token,
        a3_replay,
        a4_prompt_injection,
        a5_unauthorized_wire,
        a6_expired_token,
        a7_scope_escalation,
        a8_audit_tamper,
        a9_fake_approval,
    )
)
DEFAULT_OUT = REPO_ROOT / "docs" / "results.md"
NOT_APPLICABLE = "A9"  # baseline has no human-approval step to attack


def run_all(modes: Iterable[str] = MODES) -> list[AttackResult]:
    return [attack(mode) for mode in modes for attack in ATTACKS]


def _cell(res: AttackResult | None, *, na: bool = False) -> str:
    if res is None:
        return "-"
    if na:
        return "n/a (no human step)"
    return "ATTACK SUCCEEDED" if res.succeeded else "blocked"


def render_markdown(results: Iterable[AttackResult]) -> str:
    """One row per attack: baseline outcome vs AIMFA outcome, layer and reason code."""
    names: list[str] = []
    by_key: dict[tuple[str, str], AttackResult] = {}
    for res in results:
        if res.name not in names:
            names.append(res.name)
        by_key[(res.name, res.mode)] = res
    lines = [
        "# Attack results: baseline vs AIMFA",
        "",
        "Generated by `python attacks/run_all.py` (in-process stacks, fake data).",
        "",
        "| Attack | Baseline | AIMFA | Blocked by | Reason code |",
        "|---|---|---|---|---|",
    ]
    for name in names:
        base = by_key.get((name, MODE_BASELINE))
        aim = by_key.get((name, MODE_AIMFA))
        lines.append(
            f"| {name} | {_cell(base, na=name.startswith(NOT_APPLICABLE))} | {_cell(aim)} "
            f"| {(aim.blocked_by if aim else None) or '-'} "
            f"| {(aim.reason_code.value if aim and aim.reason_code else '-')} |"
        )
    lines += ["", "## Evidence", ""]
    for name in names:
        for mode in MODES:
            res = by_key.get((name, mode))
            if res is not None:
                lines.append(f"- **{name}** ({mode}): {res.evidence}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--mode", choices=[*MODES, "both"], default="both")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)

    modes = MODES if args.mode == "both" else (args.mode,)
    markdown = render_markdown(run_all(modes))
    print(markdown)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(markdown, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
